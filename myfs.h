/* myfs.h — общие определения для модуля ядра и userspace-программы
 *
 * Этот заголовок подключается как из кода ядра (myfs_module.c),
 * так и из userspace (myfs_tool.cpp), поэтому не должен содержать
 * kernel-only заголовков.
 */

#ifndef MYFS_H
#define MYFS_H

#include <linux/types.h>   /* __u32, __u64 и т.д. */
#include <linux/ioctl.h>   /* _IO, _IOR, _IOW макросы */

/* ──────────────────────────────────────────────
 * Константы файловой системы
 * ────────────────────────────────────────────── */

#define MYFS_MAGIC          0xDEADC0DE  /* сигнатура ФС в суперблоке     */
#define MYFS_SB_RECORD_SIZE 512         /* размер записи суперблока, байт */
#define MYFS_MAX_NAME_LEN   64          /* макс. длина имени файла (def.) */
#define MYFS_MAX_FILE_SECTS 8           /* макс. секторов на файл (def.)  */
#define MYFS_SB_OFFSET_1    0           /* сектор первой копии суперблока */
#define MYFS_SB_OFFSET_2    1           /* сектор второй копии (def.)     */

/* ──────────────────────────────────────────────
 * Структура суперблока на диске
 *
 * Запись фиксированного размера 512 байт (MYFS_SB_RECORD_SIZE),
 * размещается в начале одного сектора устройства. Реальный размер
 * сектора устройства (>=512, например 4096) хранится в поле
 * sector_size и определяется автоматически при форматировании.
 * Поле checksum считается по всем остальным полям структуры
 * (XOR 32-битных слов).
 * ────────────────────────────────────────────── */
struct myfs_super_block {
    __u32 magic;            /* MYFS_MAGIC                               */
    __u32 version;          /* версия формата ФС (сейчас 1)            */
    __u32 sector_size;      /* реальный размер сектора устройства, байт */
    __u32 total_sectors;    /* общее число секторов устройства         */
    __u32 sb_offset_1;      /* сектор первой копии суперблока          */
    __u32 sb_offset_2;      /* сектор второй копии суперблока          */
    __u32 max_name_len;     /* максимальная длина имени файла          */
    __u32 file_sectors;     /* секторов на каждый файл                 */
    __u32 data_start;       /* первый сектор с данными (после двух SB) */
    __u32 num_files;        /* количество файлов в ФС                  */
    __u8  reserved[464];    /* выравнивание до 512 байт                */
    __u32 checksum;         /* XOR-хеш всего суперблока (кроме self)   */
} __attribute__((packed));

/* ──────────────────────────────────────────────
 * Структура метаданных одного файла
 * (хранится в памяти, не на диске)
 * ────────────────────────────────────────────── */
struct myfs_file_info {
    __u32 index;            /* порядковый номер файла (0-based)  */
    __u32 start_sector;     /* первый сектор данных файла        */
    __u32 num_sectors;      /* количество секторов файла         */
    __u32 crc32;            /* CRC32 содержимого (вычисляется)   */
    char  name[MYFS_MAX_NAME_LEN]; /* имя файла ("fileNNNNN\0") */
};

/* ──────────────────────────────────────────────
 * IOCTL-команды
 *
 * Магическое число 0xBE выбрано произвольно,
 * важно, чтобы оно не пересекалось с другими
 * драйверами в системе (см. ioctl-number.txt).
 * ────────────────────────────────────────────── */
#define MYFS_IOC_MAGIC  0xBE

/* Обнулить содержимое всех файлов */
#define MYFS_IOC_ZERO_ALL       _IO(MYFS_IOC_MAGIC, 1)

/* Стереть ФС (обнулить суперблоки) */
#define MYFS_IOC_ERASE_FS       _IO(MYFS_IOC_MAGIC, 2)

/* Получить метаинформацию (хеши) всех файлов.
 * Аргумент: указатель на массив struct myfs_file_info,
 * количество элементов == num_files из суперблока.    */
#define MYFS_IOC_GET_META       _IOW(MYFS_IOC_MAGIC, 3, struct myfs_file_info *)

/* Получить маппинг секторов для заданного файла.
 * Аргумент: struct myfs_sector_map (имя файла + результат). */
#define MYFS_IOC_GET_SECTOR_MAP _IOWR(MYFS_IOC_MAGIC, 4, struct myfs_sector_map)

/* Вспомогательная структура для MYFS_IOC_GET_SECTOR_MAP */
struct myfs_sector_map {
    char  name[MYFS_MAX_NAME_LEN]; /* [in]  имя файла                 */
    __u32 file_index;   /* [out] порядковый номер найденного файла    */
    __u32 start_sector; /* [out] первый сектор файла                  */
    __u32 num_sectors;  /* [out] количество секторов файла            */
    __u32 sector_size;  /* [out] размер сектора устройства, байт      */
};

#endif /* MYFS_H */
